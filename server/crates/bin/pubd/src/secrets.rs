//! `pubd generate-secrets` — emits ready-to-use production secret material (S-25).
//!
//! Production mode refuses to boot without three secrets: the Ed25519 JWT signing key with
//! its `kid` (S-07/S-27), the OTP pepper (S-03), and the 32-byte KEK sealing data at rest
//! (S-05/S-26). This subcommand generates all of them from the OS CSPRNG and renders them
//! in the two forms the config loader accepts: a `.env` fragment (`PUB_*` keys — the
//! `docker run --env-file` path) and a TOML fragment (the `--config` file path).
//!
//! Output layout is a documented contract (pinned by `deterministic_layout_*` tests below):
//! comment header, then one key per line in a fixed order. Values are never repeated
//! between runs. Stdout by default; `--out PATH` writes the file `0600` on unix and refuses
//! to overwrite without `--force` — the file being clobbered may hold the keys a live
//! instance still verifies tokens with.

use std::io::Write as _;
use std::path::{Path, PathBuf};

use anyhow::Context as _;
use base64::Engine as _;
use base64::engine::general_purpose::STANDARD as B64;
use pub_auth::random::{OsRandom, RandomSource};

/// Which rendering(s) of the same generated material to emit.
#[derive(Debug, Clone, Copy, PartialEq, Eq, clap::ValueEnum)]
pub enum OutputFormat {
    /// `.env` fragment with `PUB_*` keys — for `docker run --env-file` or an exported
    /// environment.
    Env,
    /// TOML fragment — merge into the file passed via `--config` / `PUB_CONFIG`.
    Toml,
    /// Both fragments, separated by comment banners. Stdout only: a mixed file would be
    /// valid as neither an env file nor a TOML file.
    Both,
}

/// CLI arguments for `pubd generate-secrets`.
#[derive(Debug, clap::Args)]
pub struct GenerateSecretsArgs {
    /// Output format; the default prints both fragments of the same material.
    #[arg(long, value_enum, default_value_t = OutputFormat::Both)]
    pub format: OutputFormat,

    /// Write to PATH (created with mode 0600) instead of stdout. Requires a single
    /// format: --format env or --format toml.
    #[arg(long, value_name = "PATH")]
    pub out: Option<PathBuf>,

    /// Overwrite PATH if it already exists.
    #[arg(long)]
    pub force: bool,
}

/// One freshly generated set of production secrets.
///
/// No custom [`std::fmt::Debug`] redaction on purpose, unlike every config struct
/// (S-25.a): emitting these values is this type's entire job, it never coexists with a
/// running server, and it is dropped as soon as it is rendered.
pub struct SecretMaterial {
    /// Key id of the signing key: `YYYYMMDD-xxxxxxxx` (date for S-27 rotation ordering,
    /// four random bytes in hex against same-day collisions).
    pub kid: String,
    /// Base64 of a 32-byte Ed25519 seed (`auth.jwt.signing_key`).
    pub signing_key: String,
    /// Base64 of 32 random bytes (`auth.otp_pepper`).
    pub otp_pepper: String,
    /// Base64 of 32 random bytes (`auth.kek`, AES-256).
    pub kek: String,
}

/// Draws fresh material from `rng`. `today` only shapes the `kid` prefix.
pub fn generate(rng: &dyn RandomSource, today: chrono::NaiveDate) -> SecretMaterial {
    let mut suffix = [0u8; 4];
    rng.fill(&mut suffix);
    let kid =
        format!("{}-{:02x}{:02x}{:02x}{:02x}", today.format("%Y%m%d"), suffix[0], suffix[1], suffix[2], suffix[3]);
    SecretMaterial { kid, signing_key: random_b64(rng), otp_pepper: random_b64(rng), kek: random_b64(rng) }
}

fn random_b64(rng: &dyn RandomSource) -> String {
    let mut bytes = [0u8; 32];
    rng.fill(&mut bytes);
    B64.encode(bytes)
}

/// The `.env` rendering. Values are deliberately unquoted: `docker run --env-file` and
/// compose `env_file:` take lines verbatim and would keep quote characters as part of the
/// value.
pub fn render_env(material: &SecretMaterial) -> String {
    format!(
        "# Pub secret material — generated by `pubd generate-secrets` (S-25).\n\
         # Every value is a live credential: keep this file out of version control and logs.\n\
         # Use with `docker run --env-file <file>`, or export into pubd's environment\n\
         # (quote the values yourself when sourcing from a shell — base64 carries + / =).\n\
         PUB_SERVER__MODE=production\n\
         PUB_AUTH__JWT__KID={kid}\n\
         PUB_AUTH__JWT__SIGNING_KEY={signing_key}\n\
         PUB_AUTH__OTP_PEPPER={otp_pepper}\n\
         PUB_AUTH__KEK={kek}\n",
        kid = material.kid,
        signing_key = material.signing_key,
        otp_pepper = material.otp_pepper,
        kek = material.kek,
    )
}

/// The TOML rendering — same material, config-file form.
pub fn render_toml(material: &SecretMaterial) -> String {
    format!(
        "# Pub secret material — generated by `pubd generate-secrets` (S-25).\n\
         # Merge into the TOML file passed via --config / PUB_CONFIG.\n\
         # Every value is a live credential: keep this file out of version control and logs.\n\
         [server]\n\
         mode = \"production\"\n\
         \n\
         [auth]\n\
         otp_pepper = \"{otp_pepper}\"\n\
         kek = \"{kek}\"\n\
         \n\
         [auth.jwt]\n\
         kid = \"{kid}\"\n\
         signing_key = \"{signing_key}\"\n",
        kid = material.kid,
        signing_key = material.signing_key,
        otp_pepper = material.otp_pepper,
        kek = material.kek,
    )
}

/// Both fragments of the SAME material, banner-separated (`#` comments both dialects skip).
fn render_both(material: &SecretMaterial) -> String {
    format!(
        "# ── .env fragment ──────────────────────────────────────────────────────────\n\
         {env}\
         \n\
         # ── TOML fragment (the same material in config-file form — use one OR the other)\n\
         {toml}",
        env = render_env(material),
        toml = render_toml(material),
    )
}

/// Entry point for the subcommand.
pub fn run(args: &GenerateSecretsArgs) -> anyhow::Result<()> {
    let material = generate(&OsRandom, chrono::Utc::now().date_naive());
    let rendered = match args.format {
        OutputFormat::Env => render_env(&material),
        OutputFormat::Toml => render_toml(&material),
        OutputFormat::Both => render_both(&material),
    };
    match &args.out {
        None => {
            print!("{rendered}");
            Ok(())
        }
        Some(path) => {
            anyhow::ensure!(
                args.format != OutputFormat::Both,
                "--out needs a single format: pass --format env or --format toml"
            );
            write_out(path, &rendered, args.force).with_context(|| {
                format!("failed to write {} (pass --force to overwrite an existing file)", path.display())
            })?;
            // Confirmation on stderr so stdout stays clean for redirection.
            eprintln!("wrote {}", path.display());
            Ok(())
        }
    }
}

/// Writes `contents` to `path`; without `force` an existing file is an error, never
/// silently replaced. New files are created `0600` on unix — this is key material.
fn write_out(path: &Path, contents: &str, force: bool) -> std::io::Result<()> {
    let mut options = std::fs::OpenOptions::new();
    options.write(true);
    if force {
        options.create(true).truncate(true);
    } else {
        options.create_new(true);
    }
    #[cfg(unix)]
    {
        use std::os::unix::fs::OpenOptionsExt as _;
        options.mode(0o600);
    }
    options.open(path)?.write_all(contents.as_bytes())
}

#[cfg(test)]
mod tests {
    use std::io::Write as _;

    use pub_auth::random::FixedRandom;
    use pub_config::CliArgs;

    use super::*;

    fn day() -> chrono::NaiveDate {
        chrono::NaiveDate::from_ymd_opt(2026, 8, 7).expect("valid date")
    }

    /// Parses the `.env` rendering into the map shape `pub_config::load_from` accepts.
    fn env_map(fragment: &str) -> config::Map<String, String> {
        fragment
            .lines()
            .filter(|line| !line.starts_with('#') && !line.trim().is_empty())
            .map(|line| {
                let (key, value) = line.split_once('=').expect("env line has key=value");
                (key.to_owned(), value.to_owned())
            })
            .collect()
    }

    #[test]
    fn s07_signing_key_forms_a_valid_ed25519_keyring() {
        let material = generate(&OsRandom, day());
        pub_auth::jwt::Keyring::from_base64(&material.kid, &material.signing_key, &[])
            .expect("generated seed must build a keyring");
    }

    #[test]
    fn s25_material_decodes_to_32_bytes_each() {
        let material = generate(&OsRandom, day());
        for (name, value) in
            [("signing_key", &material.signing_key), ("otp_pepper", &material.otp_pepper), ("kek", &material.kek)]
        {
            let bytes = B64.decode(value).unwrap_or_else(|_| panic!("{name} is not base64"));
            assert_eq!(bytes.len(), 32, "{name} must be 32 bytes");
        }
    }

    #[test]
    fn two_runs_never_repeat_material() {
        let a = generate(&OsRandom, day());
        let b = generate(&OsRandom, day());
        assert_ne!(a.kid, b.kid, "kid suffix must differ between runs");
        assert_ne!(a.signing_key, b.signing_key);
        assert_ne!(a.otp_pepper, b.otp_pepper);
        assert_ne!(a.kek, b.kek);
        // The three secrets of ONE run must not repeat each other either — a generator
        // reusing its buffer would hand the KEK to whoever holds the pepper.
        assert_ne!(a.signing_key, a.otp_pepper);
        assert_ne!(a.otp_pepper, a.kek);
        assert_ne!(a.signing_key, a.kek);
    }

    #[test]
    fn s25_env_fragment_boots_production_validation() {
        let rendered = render_env(&generate(&OsRandom, day()));
        let settings = pub_config::load_from(&CliArgs::default(), Some(env_map(&rendered)))
            .expect("generated env fragment must pass production validation");
        assert_eq!(settings.server.mode, pub_config::RunMode::Production);
        assert!(settings.auth.jwt.kid.expect("kid set").starts_with("20260807-"));
    }

    #[test]
    fn s25_toml_fragment_boots_production_validation() {
        let mut file = tempfile::Builder::new().suffix(".toml").tempfile().expect("temp toml");
        file.write_all(render_toml(&generate(&OsRandom, day())).as_bytes()).expect("write temp toml");
        let cli = CliArgs { config: Some(file.path().to_path_buf()), ..CliArgs::default() };
        let settings = pub_config::load_from(&cli, Some(config::Map::new()))
            .expect("generated toml fragment must pass production validation");
        assert_eq!(settings.server.mode, pub_config::RunMode::Production);
    }

    #[test]
    fn deterministic_layout_env() {
        // The layout is a documented contract: a fixed RNG pins every byte of the output.
        let material = generate(&FixedRandom::new(vec![0xAB]), day());
        let filler = B64.encode([0xAB; 32]);
        let rendered = render_env(&material);
        let expected = format!(
            "# Pub secret material — generated by `pubd generate-secrets` (S-25).\n\
             # Every value is a live credential: keep this file out of version control and logs.\n\
             # Use with `docker run --env-file <file>`, or export into pubd's environment\n\
             # (quote the values yourself when sourcing from a shell — base64 carries + / =).\n\
             PUB_SERVER__MODE=production\n\
             PUB_AUTH__JWT__KID=20260807-abababab\n\
             PUB_AUTH__JWT__SIGNING_KEY={filler}\n\
             PUB_AUTH__OTP_PEPPER={filler}\n\
             PUB_AUTH__KEK={filler}\n"
        );
        assert_eq!(rendered, expected);
    }

    #[test]
    fn deterministic_layout_toml() {
        let material = generate(&FixedRandom::new(vec![0xAB]), day());
        let filler = B64.encode([0xAB; 32]);
        let rendered = render_toml(&material);
        let expected = format!(
            "# Pub secret material — generated by `pubd generate-secrets` (S-25).\n\
             # Merge into the TOML file passed via --config / PUB_CONFIG.\n\
             # Every value is a live credential: keep this file out of version control and logs.\n\
             [server]\n\
             mode = \"production\"\n\
             \n\
             [auth]\n\
             otp_pepper = \"{filler}\"\n\
             kek = \"{filler}\"\n\
             \n\
             [auth.jwt]\n\
             kid = \"20260807-abababab\"\n\
             signing_key = \"{filler}\"\n"
        );
        assert_eq!(rendered, expected);
    }

    #[test]
    fn out_refuses_to_overwrite_without_force_and_replaces_with_it() {
        let dir = tempfile::tempdir().expect("temp dir");
        let path = dir.path().join("secrets.env");
        write_out(&path, "first\n", false).expect("fresh write succeeds");

        let err = write_out(&path, "second\n", false).expect_err("existing file must be refused");
        assert_eq!(err.kind(), std::io::ErrorKind::AlreadyExists);
        assert_eq!(std::fs::read_to_string(&path).expect("read back"), "first\n", "file must be untouched");

        write_out(&path, "second\n", true).expect("--force overwrites");
        assert_eq!(std::fs::read_to_string(&path).expect("read back"), "second\n");
    }

    #[cfg(unix)]
    #[test]
    fn s25_out_file_is_owner_only() {
        use std::os::unix::fs::PermissionsExt as _;
        let dir = tempfile::tempdir().expect("temp dir");
        let path = dir.path().join("secrets.env");
        write_out(&path, "x\n", false).expect("write");
        let mode = std::fs::metadata(&path).expect("metadata").permissions().mode();
        assert_eq!(mode & 0o777, 0o600, "secret files must be owner-only");
    }
}
